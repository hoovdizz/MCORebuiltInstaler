function Install-TrustedRootCertificate {
    param([Parameter(Mandatory)][string]$CertPath)

    if (-not (Test-Path -LiteralPath $CertPath -PathType Leaf)) {
        throw "Required certificate is missing: $CertPath"
    }

    $cert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2($CertPath)
    $thumbprint = $cert.Thumbprint.Replace(' ','').ToUpperInvariant()

    Write-Log "Certificate subject: $($cert.Subject)"
    Write-Log "Certificate thumbprint: $thumbprint"
    Write-Log "Installing certificate into Local Computer -> Trusted Root Certification Authorities."

    # Explicitly target the LOCAL MACHINE ROOT store.
    $store = New-Object System.Security.Cryptography.X509Certificates.X509Store(
        'Root',
        [System.Security.Cryptography.X509Certificates.StoreLocation]::LocalMachine
    )

    try {
        $store.Open(
            [System.Security.Cryptography.X509Certificates.OpenFlags]::ReadWrite
        )

        $existing = $store.Certificates |
            Where-Object { $_.Thumbprint.Replace(' ','').ToUpperInvariant() -eq $thumbprint } |
            Select-Object -First 1

        if (-not $existing) {
            $store.Add($cert)
            Write-Log 'Certificate added to LocalMachine\Root.'
        }
        else {
            Write-Log 'Certificate is already present in LocalMachine\Root.'
        }
    }
    finally {
        $store.Close()
    }

    # Verify installation explicitly.
    $verifyPath = "Cert:\LocalMachine\Root\$thumbprint"
    if (-not (Test-Path -LiteralPath $verifyPath)) {
        throw "Certificate verification failed. It was not found in Local Computer -> Trusted Root Certification Authorities."
    }

    Write-Log "Verified certificate in LocalMachine\Root: $thumbprint"

    return [pscustomobject]@{
        Thumbprint = $thumbprint
        Subject    = $cert.Subject
        NotBefore  = $cert.NotBefore
        NotAfter   = $cert.NotAfter
    }
}

